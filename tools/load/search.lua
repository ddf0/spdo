-- Подбор похожих обращений: POST /api/search (Ф3), как при наборе текста
-- на странице регистрации. Запросы перебираются по кругу.
package.path = "/scripts/?.lua;" .. package.path
local common = require("common")

local queries = {
  { "Не подключается VPN", "При подключении из дома выдаёт ошибку 809, вчера всё работало" },
  { "Принтер печатает пустые листы", "В аудитории на третьем этаже МФУ выдаёт чистую бумагу" },
  { "Не приходит почта", "Письма от внешних адресатов перестали доходить с утра" },
  { "Забыл пароль от учётной записи", "Не могу войти в личный кабинет, сброс пароля не приходит" },
  { "Wi-Fi постоянно отваливается", "В корпусе на Таллинской сеть пропадает каждые пять минут" },
  { "Проектор не видит ноутбук", "Подключаю по HDMI, на экране нет сигнала" },
  { "Не открывается LMS", "Сайт с курсами выдаёт ошибку 502 при входе" },
  { "Нужно установить MATLAB", "Для лабораторной работы требуется MATLAB на компьютерах класса" },
  { "Outlook просит пароль", "После смены пароля Outlook постоянно запрашивает его снова" },
  { "Компьютер очень медленно работает", "Загрузка Windows занимает больше десяти минут" },
  { "Не работает телефон", "IP-телефон на рабочем месте не регистрируется в сети" },
  { "Ошибка при печати PDF", "Документы PDF уходят в очередь печати и пропадают" },
}

local i = 0

function init(args)
  common.seed()
  i = math.random(#queries)
end

function request()
  i = i % #queries + 1
  local q = queries[i]
  local body = string.format('{"title":"%s","description":"%s"}', q[1], q[2])
  return wrk.format("POST", "/api/search", common.headers({
    ["Content-Type"] = "application/json",
    ["X-CSRF-Token"] = common.csrf,
  }), body)
end

setup = common.setup
response = common.response
done = common.report
